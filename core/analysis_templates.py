# ============================================
# 模板函数
# ============================================

def get_scene_template(scene_type: str) -> Optional[str]:
    """
    获取指定场景的分析模板

    Args:
        scene_type: 场景类型，可选：通用决策/创业决策/职场决策/投资决策

    Returns:
        模板字符串，如果场景不存在返回None
    """
    scene = SCENE_TEMPLATES.get(scene_type)
    return scene["template"] if scene else None


def get_scene_description(scene_type: str) -> Optional[str]:
    """
    获取场景描述

    Args:
        scene_type: 场景类型

    Returns:
        场景描述字符串
    """
    scene = SCENE_TEMPLATES.get(scene_type)
    return scene["description"] if scene else None


def get_scene_focus_areas(scene_type: str) -> Optional[list]:
    """
    获取场景重点关注领域

    Args:
        scene_type: 场景类型

    Returns:
        重点关注领域列表
    """
    scene = SCENE_TEMPLATES.get(scene_type)
    return scene["focus_areas"] if scene else None


def get_all_scene_types() -> list:
    """
    获取所有可用的场景类型

    Returns:
        场景类型列表
    """
    return list(SCENE_TEMPLATES.keys())


def build_analysis_prompt(question: str, scene_type: str = "通用决策") -> str:
    """
    构建完整的分析提示词

    Args:
        question: 用户问题
        scene_type: 场景类型

    Returns:
        完整的分析提示词
    """
    template = get_scene_template(scene_type) or get_scene_template("通用决策")
    focus_areas = get_scene_focus_areas(scene_type) or []

    # 构建提示词
    prompt_parts = [
        f"## 用户问题\n{question}\n",
        f"## 场景类型\n{scene_type}\n",
    ]

    if focus_areas:
        prompt_parts.append(f"## 重点关注\n" + "\n".join(f"- {area}" for area in focus_areas) + "\n")

    prompt_parts.append(template.format(question=question))

    return "\n".join(prompt_parts)


