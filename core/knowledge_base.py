def search_tactics(keyword: str) -> list:
    """
    根据关键词搜索谋略

    Args:
        keyword: 搜索关键词

    Returns:
        匹配的谋略列表，每项包含来源和详情
    """
    if _USE_EXTERNAL_KB and _km:
        return _km.search_tactics(keyword)
    results = []
    for source, data in STRATEGY_KNOWLEDGE_BASE.items():
        tactics = data.get("core_tactics", {})
        for name, detail in tactics.items():
            if keyword.lower() in name.lower() or keyword.lower() in str(detail).lower():
                results.append({
                    "source": source,
                    "name": name,
                    "detail": detail,
                })
    return results


